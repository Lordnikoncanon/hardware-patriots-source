export function isBambuBrand(brand: string): boolean {
  return brand.trim().toLowerCase() === "bambu lab";
}

export function bambuTypes(): string[] {
  const seen = new Set<string>();
  const types: string[] = [];
  for (const color of BAMBU_COLORS) {
    if (seen.has(color.type)) continue;
    seen.add(color.type);
    types.push(color.type);
  }
  return types;
}

export function bambuColorsFor(type: string): BambuColor[] {
  return BAMBU_COLORS.filter((color) => color.type === type);
}

export function bambuCostCents(type: string): number | null {
  return BAMBU_SPOOL_COST_CENTS[type] ?? null;
}

